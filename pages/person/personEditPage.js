const { expect } = require('@playwright/test');
const { PersonPage } = require('./personPage');

const TEXT_FIELDS = ['firstName', 'middleName', 'lastName', 'handle', 'email'];

/**
 * Person detail / edit page: /Person/Edit/{id} (use case 62386 View & Update Person).
 * Same field ids as Add Person, plus Display Name, Initials, Save/Cancel and the record tabs.
 * Extends PersonPage so a test can create the person it edits (createPerson).
 */
class PersonEditPage extends PersonPage {
  constructor(page) {
    super(page);
    this.displayName = page.getByLabel('Display Name', { exact: true });
    this.initials = page.getByLabel('Initials', { exact: true });
    this.saveButton = page.getByRole('button', { name: 'Save', exact: true });
    this.cancelEditButton = page.getByRole('button', { name: 'Cancel', exact: true }).or(page.getByRole('link', { name: 'Cancel', exact: true }));
  }

  async gotoEdit(id) {
    await this.openRecord(`/Person/Edit/${id}`);
    await expect(this.page).toHaveURL(new RegExp(`/Person/Edit/${id}(?:[/?#]|$)`));
    await expect(this.firstName).toBeVisible();
  }

  /** Changes only the keys present in `u`; an empty string clears the field. Phone/address go through the drawers. */
  async updateForm(u) {
    for (const key of TEXT_FIELDS) {
      if (key in u) await this[key].fill(u[key] || '');
    }
    if (u.phone) {
      await this.phoneDrawer.add(u.phone);
      await this.closeDrawerIfOpen();
    }
    if (u.address) {
      await this.addressDrawer.add(u.address);
      await this.closeDrawerIfOpen();
    }
  }

  /** Clicks Save and waits for the post-back and the confirmation message (MF-7 to MF-9). */
  async save() {
    await this.saveRecord(this.saveButton, 'person');
    await expect(this.page).toHaveURL(/\/Person\/Edit\/\d+/);
  }

  /** Clicks Save for a negative test and waits for either the validation message or a (wrong) save confirmation. */
  async trySave(expectedMessage) {
    await this.saveButton.click();
    await expect(this.validationMessage(expectedMessage).or(this.savedMessage)).toBeVisible({ timeout: 30_000 });
  }

  /** Display Name / Initials as generated by 62247: "First Last" and the two first letters. */
  static displayNameOf(p) {
    return [p.firstName, p.lastName].filter(Boolean).join(' ');
  }

  static initialsOf(p) {
    return [p.firstName, p.lastName].filter(Boolean).map(s => s[0].toUpperCase()).join('');
  }

  /** Every value of `p` is shown on the open record (fields, header, phone and address lists). */
  async expectDetails(p) {
    await expect(this.page).toHaveURL(/\/Person\/Edit\/\d+/);
    await expect(this.firstName).toHaveValue(p.firstName || '');
    await expect(this.middleName).toHaveValue(p.middleName || '');
    await expect(this.lastName).toHaveValue(p.lastName || '');
    if (p.handle) await expect(this.handle).toHaveValue(p.handle);
    await expect(this.email).toHaveValue(p.email || '');
    if (p.phone) await expect(this.phoneText(p.phone.number)).toBeVisible();
    if (p.address) await expect(this.page.locator('main').getByText(p.address.address1).first()).toBeVisible();

    const display = PersonEditPage.displayNameOf(p);
    await expect(this.displayName, 'Display Name should be maintained by 62247').toHaveValue(display);
    await expect(this.initials, 'Initials should be maintained by 62247').toHaveValue(PersonEditPage.initialsOf(p));
    await expect(this.page.locator('main').getByText(display, { exact: true }).first(), 'Header shows the Display Name').toBeVisible();
    if (p.handle) await expect(this.page.locator('main').getByText(`@${p.handle}`, { exact: true }).first(), 'Header shows the @handle').toBeVisible();
  }
}

module.exports = { PersonEditPage };
